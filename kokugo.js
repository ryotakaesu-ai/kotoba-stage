/* ================= 4択の組み立て ================= */
function distinct(correct, cands, n) {
  const out = [];
  const seen = new Set([correct]);
  for (const c of shuffle(cands)) {
    if (out.length >= n) break;
    if (!seen.has(c)) { seen.add(c); out.push(c); }
  }
  return out;
}
function mk(qHtml, correct, wrongs, tag, opt) {
  const choices = shuffle([correct, ...wrongs.slice(0, 3)]);
  return Object.assign({ q: qHtml, choices, a: { t: "choice", text: correct }, tag, small: true }, opt || {});
}
const B = s => `<b style="font-size:1.25em">${s}</b>`;

/* ---------- ① 漢字の読み ---------- */
function gYomi(lv) {
  const tier = YOMI[lv - 1];
  const it = pick(tier);
  const pool = YOMI.flat().map(x => x[1]);
  const wrongs = [it[2], ...distinct(it[1], pool.filter(x => x !== it[2]), 2)];
  return mk(`「 ${B(it[0])} 」<br>の読み方は？`, it[1], shuffle(wrongs), "漢字の読み");
}

/* ---------- ② 慣用句（IDIOMS 352問） ---------- */
function gKanyoku(lv) {
  const it = pick(IDIOMS);
  const sameCat = IDIOMS.filter(x => x.c === it.c && x.i !== it.i);
  const anyCat = IDIOMS.filter(x => x.i !== it.i);
  const src = lv >= 3 && sameCat.length >= 3 ? sameCat : anyCat;
  if (lv >= 4 && Math.random() < .5) {
    /* 意味 → 慣用句 */
    const wrongs = distinct(it.i, src.map(x => x.i), 3);
    return mk(`「${it.m}」<br>という意味の慣用句は？`, it.i, wrongs, "慣用句");
  }
  const wrongs = distinct(it.m, src.map(x => x.m), 3);
  return mk(`「 ${B(it.i)} 」<br>の意味は？`, it.m, wrongs, "慣用句");
}

/* ---------- ③ ことわざ ---------- */
function gKotowaza(lv) {
  const tier = KOTOWAZA[lv - 1];
  const it = pick(tier);
  const pool = KOTOWAZA.flat();
  if (lv >= 4 && Math.random() < .45) {
    const wrongs = distinct(it[0], pool.map(x => x[0]), 3);
    return mk(`「${it[1]}」<br>という意味のことわざは？`, it[0], wrongs, "ことわざ");
  }
  const wrongs = distinct(it[1], pool.map(x => x[1]), 3);
  return mk(`「 ${B(it[0])} 」<br>の意味は？`, it[1], wrongs, "ことわざ");
}

/* ---------- ④ 四字熟語 ---------- */
const NUMCHARS = "一二三四五六七八九十百千万";
function gYoji(lv) {
  const it = pick(YOJI);
  if (lv <= 2 || (lv === 3 && Math.random() < .5)) {
    const wrongs = distinct(it[1], YOJI.map(x => x[1]), 3);
    return mk(`「 ${B(it[0])} 」<br>の意味は？`, it[1], wrongs, "四字熟語");
  }
  /* 空欄補充：1文字を隠す（数字があれば数字を優先） */
  const w = it[0];
  const numIdx = [...w].map((c, i) => NUMCHARS.includes(c) ? i : -1).filter(i => i >= 0);
  const h = numIdx.length && Math.random() < .7 ? pick(numIdx) : ri(0, 3);
  const correct = w[h];
  const disp = w.slice(0, h) + "□" + w.slice(h + 1);
  const charPool = YOJI.map(x => x[0][h]).filter(c => c && c !== correct);
  const wrongs = distinct(correct, charPool, 3);
  return mk(`四字熟語の □ に入る字は？<br>「 ${B(disp)} 」<br><span style="font-size:.85em;opacity:.75">（${it[1]}）</span>`, correct, wrongs, "四字熟語");
}

/* ---------- ⑤ 対義語・類義語 ---------- */
function gGoi(lv) {
  const useRui = lv >= 4 ? Math.random() < .55 : Math.random() < .2;
  const bank = useRui ? RUIGI : TAIGI;
  const it = pick(bank);
  const flip = Math.random() < .5;
  const qw = flip ? it[1] : it[0], ans = flip ? it[0] : it[1];
  const pool = bank.flat().concat((useRui ? TAIGI : RUIGI).flat().slice(0, 20));
  const wrongs = distinct(ans, pool.filter(x => x !== qw), 3);
  return mk(`「 ${B(qw)} 」の${useRui ? "類義語（にた意味の言葉）" : "対義語（反対の言葉）"}は？`, ans, wrongs, useRui ? "類義語" : "対義語");
}

/* ---------- ⑥ 敬語 ---------- */
function gKeigo(lv) {
  for (let i = 0; i < 30; i++) {
    const it = pick(KEIGO);
    const sonkei = lv <= 2 ? true : lv >= 4 ? Math.random() < .4 : Math.random() < .6;
    const ans = sonkei ? it[1] : it[2];
    if (ans === "（なし）") continue;
    const trap = sonkei ? it[2] : it[1];
    const pool = KEIGO.flatMap(x => [x[1], x[2]]).filter(x => x !== "（なし）" && x !== ans);
    const wrongs = shuffle([...(trap !== "（なし）" ? [trap] : []), ...distinct(ans, pool.filter(x => x !== trap), trap !== "（なし）" ? 2 : 3)]).slice(0, 3);
    return mk(
      sonkei
        ? `「先生が${B(it[0])}」<br>正しい尊敬語は？<br><span style="font-size:.8em;opacity:.75">（相手を高める言い方）</span>`
        : `「わたしが${B(it[0])}」<br>正しい謙譲語は？<br><span style="font-size:.8em;opacity:.75">（自分をへりくだる言い方）</span>`,
      ans, wrongs, "敬語");
  }
  return gKeigo(2);
}

